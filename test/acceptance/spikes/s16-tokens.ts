/**
 * Spike S16: the token generator of the specification, 7.7, and the theme function of 7.12, written as the
 * specification states them. It is spike code. The kit will have its own `renderTokens` (`src/design/tokens.ts`)
 * and `themeOf` (`src/modes.ts`).
 */

export type Theme = 'light' | 'dark' | 'light-contrast' | 'dark-contrast';
export type Option = 'auto' | 'light' | 'dark' | 'contrast';
export type Level = 'std' | 'more';

export const THEMES: readonly Theme[] = ['light', 'dark', 'light-contrast', 'dark-contrast'];
export const OPTIONS: readonly Option[] = ['auto', 'light', 'dark', 'contrast'];

/** What `renderTokens` reads from `docs/design.md` (7.4). Cells are trimmed, with backticks stripped. */
export interface Design {
  /** The rows of `## Themes`. */
  themes: Theme[];
  /** The rows of `## Color`. A missing or empty cell is an empty cell. A cell of a theme that is not declared is no column. */
  colors: { token: string; cells: Partial<Record<Theme, string>> }[];
  /** The rows of the other token sections, in the section order of 7.7 step 3.3. */
  others: [token: string, value: string][];
  /** The rows of `## Layout helpers`. */
  helpers: [parameter: string, token: string][];
}

/** `modes` of `astro-kit.json` (5.2). */
export interface Modes {
  auto?: boolean;
  light?: boolean;
  dark?: boolean;
  contrast?: boolean;
  default?: 'light' | 'dark' | 'contrast';
}

/** A system state `S` of 7.12. */
export interface System {
  scheme: 'light' | 'dark';
  contrast: 'no-preference' | 'more';
}

/** The four system states, in the order of section 8 (Themes). */
export const SYSTEMS: readonly System[] = [
  { scheme: 'light', contrast: 'no-preference' },
  { scheme: 'dark', contrast: 'no-preference' },
  { scheme: 'light', contrast: 'more' },
  { scheme: 'dark', contrast: 'more' },
];

/** The list `enabled` of 7.12. */
export const enabledOf = (modes: Modes): Option[] => OPTIONS.filter((option) => modes[option] === true);

/** The default mode `D` of 7.12. */
export const defaultOf = (modes: Modes): Option => (modes.auto === true ? 'auto' : (modes.default as Option));

const declares = (design: Design, theme: Theme): boolean => design.themes.includes(theme);

const CHAIN: Record<Theme, Theme[]> = {
  light: ['light'],
  dark: ['dark', 'light'],
  'light-contrast': ['light-contrast', 'light'],
  'dark-contrast': ['dark-contrast', 'dark', 'light'],
};

/** `value(t, X)` of 7.7: the cell, or the value of the next declared theme with a value (7.4). */
export function value(design: Design, token: string, theme: Theme): string {
  const row = design.colors.find((color) => color.token === token);
  if (!row) throw new Error(`${token} is no color token`);
  for (const next of CHAIN[theme]) {
    const cell = declares(design, next) ? (row.cells[next] ?? '').trim() : '';
    if (cell !== '') return cell;
  }
  throw new Error(`design-format: ${token} has no value for ${theme}`);
}

/** `pair(t, c)` of 7.7. */
export function pair(design: Design, token: string, contrast: Level): string {
  const L = (): string => value(design, token, contrast === 'std' ? 'light' : 'light-contrast');
  const K = (): string => value(design, token, contrast === 'std' ? 'dark' : 'dark-contrast');
  if (declares(design, 'light') && declares(design, 'dark')) return L() === K() ? L() : `light-dark(${L()}, ${K()})`;
  return declares(design, 'light') ? L() : K();
}

/** `level(m)` of 7.7. */
export const level = (mode: Option): Level => (mode === 'contrast' ? 'more' : 'std');

/** `scheme(m)` of 7.7. */
export function scheme(design: Design, mode: Option): string {
  if (mode === 'light' || mode === 'dark') return mode;
  if (declares(design, 'light') && declares(design, 'dark')) return 'light dark';
  return declares(design, 'light') ? 'light' : 'dark';
}

/** `expr(t, m)` of 7.7. */
export const expr = (design: Design, token: string, mode: Option): string => pair(design, token, level(mode));

export const HEADER =
  '/* Generated by @raess/astro-kit from docs/design.md. Do not edit: run npx --no astro-kit tokens. */';

/** The lines of a rule at nesting depth `depth`. No line when it has no declaration (7.7 step 4). */
function rule(depth: number, selector: string, declarations: string[]): string[] {
  if (declarations.length === 0) return [];
  const pad = '  '.repeat(depth);
  return [`${pad}${selector} {`, ...declarations.map((declaration) => `${pad}  ${declaration}`), `${pad}}`];
}

/** The selector of the media rule of step 5. It is the same with one enabled option and with more. */
export const MEDIA_SELECTOR = ':root:not([data-mode]), :root[data-mode="auto"]';

/** The text of `src/styles/tokens.css`: steps 1 to 6 of 7.7. */
export function renderTokens(design: Design, modes: Modes): string {
  const enabled = enabledOf(modes);
  const D = defaultOf(modes);
  const tokens = design.colors.map((color) => color.token);
  const lines = [HEADER, '@layer tokens {'];
  // Step 3.
  lines.push(
    ...rule(1, ':root', [
      `color-scheme: ${scheme(design, D)};`,
      ...tokens.map((token) => `${token}: ${expr(design, token, D)};`),
      ...design.others.map(([token, text]) => `${token}: ${text};`),
      ...design.helpers.map(([parameter, token]) => `${parameter}: ${token};`),
    ]),
  );
  // Step 4.
  if (enabled.length >= 2) {
    for (const mode of (['light', 'dark', 'contrast'] as const).filter(
      (option) => enabled.includes(option) && option !== D,
    )) {
      lines.push(
        ...rule(1, `:root[data-mode="${mode}"]`, [
          ...(scheme(design, mode) === scheme(design, D) ? [] : [`color-scheme: ${scheme(design, mode)};`]),
          ...tokens
            .filter((token) => expr(design, token, mode) !== expr(design, token, D))
            .map((token) => `${token}: ${expr(design, token, mode)};`),
        ]),
      );
    }
  }
  // Step 5.
  const contrasted = tokens.filter((token) => pair(design, token, 'more') !== pair(design, token, 'std'));
  if (D === 'auto' && contrasted.length > 0) {
    lines.push(
      '  @media (prefers-contrast: more) {',
      ...rule(
        2,
        MEDIA_SELECTOR,
        contrasted.map((token) => `${token}: ${pair(design, token, 'more')};`),
      ),
      '  }',
    );
  }
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

/** `schemeOf(S)` of 7.12. */
export function schemeOf(design: Design, system: System): 'light' | 'dark' {
  if (declares(design, system.scheme)) return system.scheme;
  return declares(design, 'light') ? 'light' : 'dark';
}

/** The theme function `T(mode, S)` of 7.12. */
export function themeOf(design: Design, mode: Option, system: System): Theme {
  if (mode === 'light' || mode === 'dark') return mode;
  const base = schemeOf(design, system);
  const contrast: Theme = `${base}-contrast`;
  if (mode === 'contrast') return contrast;
  return system.contrast === 'more' && declares(design, contrast) ? contrast : base;
}

const ALIAS = /^var\((--color-[a-z0-9-]+)\)$/;

/** The design.md value of a color token in a theme, with the fallback of empty cells and aliases resolved (8, `modes-behavior`). */
export function designValue(design: Design, token: string, theme: Theme): string {
  let text = value(design, token, theme);
  for (let depth = 0; depth < 8; depth += 1) {
    const alias = ALIAS.exec(text)?.[1];
    if (!alias) return text;
    text = value(design, alias, theme);
  }
  throw new Error(`${token} is an alias loop`);
}

/**
 * What 7.4 (`design-format`, the themes and the cells), 5.2 (`modes`) and 7.12 (`modes-themes`) say against a
 * design with a `modes` setting. The list is empty for a pair that `renderTokens` may get.
 */
export function problems(design: Design, modes: Modes): string[] {
  const out: string[] = [];
  const has = (theme: Theme): boolean => declares(design, theme);
  const enabled = enabledOf(modes);
  if (!has('light') && !has('dark')) out.push('themes: no base theme');
  if (has('light-contrast') && !has('light')) out.push('themes: light-contrast needs light');
  if (has('dark-contrast') && !has('dark')) out.push('themes: dark-contrast needs dark');
  for (const { token } of design.colors) {
    for (const theme of design.themes) {
      try {
        value(design, token, theme);
      } catch {
        out.push(`design-format: ${token} has an empty cell for ${theme} with no fallback`);
      }
    }
  }
  if (enabled.length === 0) out.push('modes: no option is on');
  if (modes.auto === true && modes.default !== undefined) out.push('modes.default is only for modes.auto false');
  if (modes.auto !== true && !(modes.default !== undefined && enabled.includes(modes.default))) {
    out.push('modes.default must name an option of modes that is true');
  }
  const on = (option: Option): boolean => enabled.includes(option);
  if (on('auto') && !has('light')) out.push('modes-themes: auto needs light');
  if (on('light') && !has('light')) out.push('modes-themes: light needs light');
  if (on('dark') && !has('dark')) out.push('modes-themes: dark needs dark');
  if (on('contrast') && has('light') && !has('light-contrast')) out.push('modes-themes: contrast needs light-contrast');
  if (on('contrast') && has('dark') && !has('dark-contrast')) out.push('modes-themes: contrast needs dark-contrast');
  if (has('light') && !on('auto') && !on('light')) out.push('modes-themes: no option reaches light');
  if (has('dark') && !on('auto') && !on('dark')) out.push('modes-themes: no option reaches dark');
  for (const theme of ['light-contrast', 'dark-contrast'] as const) {
    if (has(theme) && !on('auto') && !on('contrast')) out.push(`modes-themes: no option reaches ${theme}`);
  }
  return out;
}

/** The eight theme sets that 7.4 allows. */
export const THEME_SETS: Theme[][] = [
  ['light'],
  ['dark'],
  ['light', 'dark'],
  ['light', 'light-contrast'],
  ['dark', 'dark-contrast'],
  ['light', 'dark', 'light-contrast'],
  ['light', 'dark', 'dark-contrast'],
  ['light', 'dark', 'light-contrast', 'dark-contrast'],
];

/** Every `modes` setting that 5.2 allows: 8 with `auto`, and 12 without it. */
export function modesSettings(): Modes[] {
  const out: Modes[] = [];
  for (let bits = 0; bits < 16; bits += 1) {
    const modes: Modes = {
      auto: (bits & 8) !== 0,
      light: (bits & 4) !== 0,
      dark: (bits & 2) !== 0,
      contrast: (bits & 1) !== 0,
    };
    if (modes.auto) out.push(modes);
    else
      for (const option of ['light', 'dark', 'contrast'] as const)
        if (modes[option]) out.push({ ...modes, default: option });
  }
  return out;
}

/** A short name of a `modes` setting, for a file name: `auto+light+dark` or `light+dark+contrast=light`. */
export const modesName = (modes: Modes): string =>
  enabledOf(modes).join('+') + (modes.auto === true ? '' : `=${modes.default}`);
