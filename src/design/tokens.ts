/**
 * The token generator (specification, 7.7): the text of `src/styles/tokens.css` from `docs/design.md` and the
 * mode options, and the source half of the rule `design-tokens`.
 *
 * The project never writes `tokens.css`. `astro-kit tokens` writes the text of `renderTokens`, and `design-tokens`
 * compares the file with it. So the design document and the CSS cannot differ.
 */
import { readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import type { ColorToken, Design } from '../context.ts';
import { defaultMode, enabledModes, type ModeOption, type Theme } from '../modes.ts';
import type { Options } from '../options.ts';
import type { Report } from '../registry.ts';
import { firstDifference } from '../shims.ts';
import { THEME_FALLBACKS } from './parse.ts';

const RULE = 'design-tokens';

/** The file that the kit renders, from the project root. */
export const TOKENS_FILE = 'src/styles/tokens.css';

/** Line 1 of the file (7.7, step 1). */
export const TOKENS_HEADER =
  '/* Generated by @raess/astro-kit from docs/design.md. Do not edit: run npx --no astro-kit tokens. */';

/** The selector of the one rule in the `prefers-contrast` block (7.7, step 5). */
const MEDIA_SELECTOR = ':root:not([data-mode]), :root[data-mode="auto"]';

/** The options that can have a rule of their own, in the order of 7.7, step 4. */
const MODE_RULES: readonly ModeOption[] = ['light', 'dark', 'contrast'];

/** The contrast level of 7.7: `std` or `more`. */
type Level = 'std' | 'more';

/**
 * `value(t, X)` of 7.7: the cell of the color for the theme. When the theme is not declared, or the cell is empty,
 * it is the value of the next theme along `dark-contrast` → `dark` → `light`, or along `light-contrast` → `light`
 * (7.4). It is `undefined` when no theme of that chain has a value.
 */
export function colorValue(color: ColorToken, theme: Theme): string | undefined {
  for (const next of THEME_FALLBACKS[theme]) {
    const value = color.values[next];
    if (value !== undefined) return value;
  }
  return undefined;
}

/** `value(t, X)` for a design that passed `design-format`: there the value exists. */
function cellValue(color: ColorToken, theme: Theme): string {
  const value = colorValue(color, theme);
  if (value === undefined) throw new Error(`astro-kit: ${color.name} has no value for the theme ${theme}`);
  return value;
}

/** The terms of 7.7 for one design. */
interface Terms {
  /** `pair(t, c)`: the CSS value of a color at a contrast level. */
  pair: (color: ColorToken, level: Level) => string;
  /** `scheme(m)`: the `color-scheme` of a mode option. */
  scheme: (mode: ModeOption) => string;
}

function termsOf(design: Pick<Design, 'themes'>): Terms {
  const light = design.themes.includes('light');
  const dark = design.themes.includes('dark');
  const both = light && dark;
  const one = light ? 'light' : 'dark';
  return {
    pair: (color, level) => {
      const L = (): string => cellValue(color, level === 'std' ? 'light' : 'light-contrast');
      const K = (): string => cellValue(color, level === 'std' ? 'dark' : 'dark-contrast');
      if (!both) return light ? L() : K();
      return L() === K() ? L() : `light-dark(${L()}, ${K()})`;
    },
    scheme: (mode) => {
      if (mode === 'light' || mode === 'dark') return mode;
      return both ? 'light dark' : one;
    },
  };
}

/** `level(m)` of 7.7. */
const levelOf = (mode: ModeOption): Level => (mode === 'contrast' ? 'more' : 'std');

/** The lines of one rule at a nesting depth. A rule with no declaration has no line (7.7, step 4). */
function rule(depth: number, selector: string, declarations: readonly string[]): string[] {
  if (declarations.length === 0) return [];
  const pad = '  '.repeat(depth);
  return [`${pad}${selector} {`, ...declarations.map((declaration) => `${pad}  ${declaration}`), `${pad}}`];
}

/**
 * The text of `src/styles/tokens.css` (7.7, steps 1 to 6). It is pure, and it changes no value. It is for a
 * design that passed `design-format` and for mode options that passed `modes-themes`.
 */
export function renderTokens(design: Design, options: Pick<Options, 'modes'>): string {
  const enabled = enabledModes(options);
  const D = defaultMode(options);
  const { pair, scheme } = termsOf(design);
  const expr = (color: ColorToken, mode: ModeOption): string => pair(color, levelOf(mode));
  const lines = [TOKENS_HEADER, '@layer tokens {'];
  // Step 3: the no-attribute state.
  lines.push(
    ...rule(1, ':root', [
      `color-scheme: ${scheme(D)};`,
      ...design.colors.map((color) => `${color.name}: ${expr(color, D)};`),
      ...design.tokens.map((token) => `${token.name}: ${token.value};`),
      ...design.helpers.map((helper) => `${helper.name}: ${helper.token};`),
    ]),
  );
  // Step 4: one rule for each other enabled option.
  if (enabled.length >= 2) {
    for (const mode of MODE_RULES) {
      if (mode === D || !enabled.includes(mode)) continue;
      lines.push(
        ...rule(1, `:root[data-mode="${mode}"]`, [
          ...(scheme(mode) === scheme(D) ? [] : [`color-scheme: ${scheme(mode)};`]),
          ...design.colors
            .filter((color) => expr(color, mode) !== expr(color, D))
            .map((color) => `${color.name}: ${expr(color, mode)};`),
        ]),
      );
    }
  }
  // Step 5: the contrast setting of the system, for the option `auto`.
  const contrasted = design.colors.filter((color) => pair(color, 'more') !== pair(color, 'std'));
  if (D === 'auto' && contrasted.length > 0) {
    lines.push(
      '  @media (prefers-contrast: more) {',
      ...rule(
        2,
        MEDIA_SELECTOR,
        contrasted.map((color) => `${color.name}: ${pair(color, 'more')};`),
      ),
      '  }',
    );
  }
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

/**
 * The source half of `design-tokens`: `src/styles/tokens.css` equals `renderTokens` of the design and the mode
 * options, after CRLF→LF and trimEnd + newline. It adds at most one finding: the file is missing, or the first
 * line that differs.
 */
export function checkTokens(root: string, design: Design, options: Pick<Options, 'modes'>, report: Report): void {
  const path = join(root, TOKENS_FILE);
  const stats = statSync(path, { throwIfNoEntry: false });
  if (stats === undefined) {
    report.add(RULE, TOKENS_FILE, 'the file is missing');
    return;
  }
  if (!stats.isFile()) {
    report.add(RULE, TOKENS_FILE, 'this is not a file');
    return;
  }
  const difference = firstDifference(readFileSync(path, 'utf8'), renderTokens(design, options));
  if (difference === undefined) return;
  const expected =
    difference.expected === undefined
      ? 'the rendering ends before this line'
      : `the rendering has \`${difference.expected.trim()}\` here`;
  report.add(RULE, `${TOKENS_FILE}:${difference.line}`, expected);
}
